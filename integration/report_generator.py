from datetime import datetime, timezone
from typing import Any

def generate_screening_report(case_id: str, payload: dict[str, Any]) -> dict[str, Any]:
    """
    Generates a structured clinical screening report and Markdown representation.
    """
    generated_at = datetime.now(timezone.utc).isoformat()
    quality = payload.get("quality", {})
    classification = payload.get("classification") or {}
    explainability = payload.get("explainability") or {}
    decision = payload.get("clinical_decision", {})

    grade_name = classification.get("grade_name", "Ungraded")
    grade_num = classification.get("predicted_grade", "N/A")
    conf = explainability.get("calibrated_confidence", 0.0)
    referral = "YES" if decision.get("referral_recommended") else "NO"
    urgency = decision.get("urgency", "routine").replace("_", " ").upper()
    rationale = decision.get("rationale", "N/A")
    action = decision.get("action_required", "N/A")

    markdown_text = f"""# EYERIS — Diabetic Retinopathy Screening Report
**Case ID**: `{case_id}`  
**Report Generated**: {generated_at}  
**Status**: {payload.get("status", "completed").upper()}  

---

### Clinical Screening Summary
- **DR Severity Grade**: **Grade {grade_num} ({grade_name})**
- **Calibrated Confidence**: {conf:.1%}
- **Referral Recommended**: **{referral}**
- **Escalation Urgency**: **{urgency}**

### Decision Rationale
> {rationale}

### Recommended Next Action
> {action}

---

### Image Quality Assessment
- **Gradable**: {"Yes" if quality.get("is_gradable", True) else "No"}
- **Quality Score**: {quality.get("overall_quality_score", 0.0):.2f} / 1.00
- **Sharpness**: {quality.get("metrics", {}).get("sharpness_score", 0.0):.2f}
- **Illumination**: {quality.get("metrics", {}).get("illumination_score", 0.0):.2f}
- **Contrast**: {quality.get("metrics", {}).get("contrast_score", 0.0):.2f}

---

> **IMPORTANT MEDICAL NOTICE**:  
> This report was generated by an experimental research screening prototype (EYERIS) developed for SIH Problem Statement PS26038. It does NOT constitute a definitive medical diagnosis. All findings and referral recommendations must be confirmed by a licensed optometrist or ophthalmologist.
"""

    return {
        "report_id": f"REP-{case_id}",
        "case_id": case_id,
        "generated_at": generated_at,
        "summary_markdown": markdown_text,
        "screening_result": payload,
    }
